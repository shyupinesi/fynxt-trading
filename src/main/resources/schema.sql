-- ============================================================
-- FYNXT Trading Platform - Database Schema
-- ============================================================

-- Traders table
CREATE TABLE IF NOT EXISTS traders (
    id          VARCHAR(50)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_traders PRIMARY KEY (id)
);

-- Orders table
CREATE TABLE IF NOT EXISTS orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    trader_id   VARCHAR(50)  NOT NULL,
    stock       VARCHAR(20)  NOT NULL,
    sector      VARCHAR(50)  NOT NULL,
    quantity    INT          NOT NULL,
    side        VARCHAR(10)  NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT fk_orders_trader
        FOREIGN KEY (trader_id) REFERENCES traders(id),

    CONSTRAINT chk_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_side
        CHECK (side IN ('BUY', 'SELL')),

    CONSTRAINT chk_status
        CHECK (status IN ('PENDING', 'FILLED', 'CANCELLED'))
);

-- Used for:
-- "A trader cannot have more than 3 pending orders"
CREATE INDEX IF NOT EXISTS idx_orders_trader_status
    ON orders (trader_id, status);

-- Portfolio holdings table
CREATE TABLE IF NOT EXISTS portfolio_positions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    trader_id   VARCHAR(50)  NOT NULL,
    stock       VARCHAR(20)  NOT NULL,
    sector      VARCHAR(50)  NOT NULL,
    quantity    INT          NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_portfolio PRIMARY KEY (id),

    CONSTRAINT fk_portfolio_trader
        FOREIGN KEY (trader_id) REFERENCES traders(id),

    CONSTRAINT uq_portfolio_pos
        UNIQUE (trader_id, stock),

    CONSTRAINT chk_portfolio_qty
        CHECK (quantity >= 0)
);

-- Fast portfolio lookup per trader
CREATE INDEX IF NOT EXISTS idx_portfolio_trader
    ON portfolio_positions (trader_id);